#!/bin/sh
# Re-copies third-party skills from skill-sources.txt at upstream HEAD. Review the git diff, then commit.
# Usage: sh copilot/sync-skills.sh [owner/repo ...]
set -eu

here="$(cd "$(dirname "$0")" && pwd)"
skills="$here/skills"
lock="$here/skills.lock"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Fetch everything first so a failed clone leaves the skills folder untouched.
grep -vE '^[[:space:]]*(#|$)' "$here/skill-sources.txt" > "$tmp/all-sources"
if [ "$#" -gt 0 ]; then
    for repo in "$@"; do
        if ! awk -v repo="$repo" '$1 == repo { print; found = 1 } END { exit !found }' "$tmp/all-sources" >> "$tmp/selected"; then
            echo "sync-skills: unknown source '$repo'" >&2
            exit 1
        fi
    done
    awk '!seen[$1]++' "$tmp/selected" > "$tmp/sources"
else
    cp "$tmp/all-sources" "$tmp/sources"
fi
while read -r repo path skip include; do
    dir="$tmp/$(echo "$repo" | tr / _)"
    git clone -q --depth 1 "https://github.com/$repo" "$dir"
    if [ -n "${include:-}" ]; then
        printf '%s\n' "$include" | tr ',' '\n' | while IFS= read -r name; do
            if [ ! -f "$dir/$path/$name/SKILL.md" ]; then
                echo "sync-skills: missing included skill '$name' in $repo" >&2
                exit 1
            fi
        done
    fi
done < "$tmp/sources"

echo "# Generated by sync-skills.sh: <repo> <commit> <skill>" > "$tmp/lock"
# Drop only refreshed sources; preserve the other sources' files and lock entries.
if [ -f "$lock" ]; then
    awk 'NR == FNR { selected[$1] = 1; next } !/^#/ && !($1 in selected)' "$tmp/sources" "$lock" >> "$tmp/lock"
    awk 'NR == FNR { selected[$1] = 1; next } !/^#/ && ($1 in selected)' "$tmp/sources" "$lock" | while read -r repo sha name; do
        rm -rf "${skills:?}/$name"
    done
fi

mkdir -p "$here/licenses"
count=0
while read -r repo path skip include; do
    dir="$tmp/$(echo "$repo" | tr / _)"
    sha="$(git -C "$dir" rev-parse HEAD)"
    for src in "$dir/$path"/*; do
        [ -f "$src/SKILL.md" ] || continue
        case ",${skip:-}," in *",$(basename "$src"),"*) continue ;; esac
        if [ -n "${include:-}" ]; then
            case ",$include," in *",$(basename "$src"),"*) ;; *) continue ;; esac
        fi
        # Folder must match the skill's declared name.
        name="$(sed -n 's/^name:[[:space:]]*//p' "$src/SKILL.md" | head -1 | tr -d "\"'\r")"
        [ -n "$name" ] || name="$(basename "$src")"
        if [ -e "$skills/$name" ]; then
            echo "sync-skills: '$name' from $repo collides with an existing skill" >&2
            exit 1
        fi
        cp -R "$src" "$skills/$name"
        echo "$repo $sha $name" >> "$tmp/lock"
        count=$((count + 1))
    done
    for license in "$dir"/LICENSE*; do
        [ -f "$license" ] && cp "$license" "$here/licenses/$(echo "$repo" | tr / _)-LICENSE"
    done
done < "$tmp/sources"

mv "$tmp/lock" "$lock"
echo "sync-skills: $count skills refreshed. Review with: git -C \"$here\" diff --stat"
